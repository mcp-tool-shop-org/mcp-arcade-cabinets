// What a piece is a picture of.
//
// The preview packs one block per shipped request, and slice 4B gives each
// block a painted tile. A tile needs a kind, and the sim does not have one:
// `BuiltPiece` is `{ id, size }` and stays that way, because the play-throughs
// are byte-identical runs of the sim and a field added there would move them.
// So the kind is derived here, in the shell, from the snippet the request just
// shipped — a pure function of what the corpus already says.
//
// Two steps, in this order:
//
//  1. The snippet's own topics, first match wins. A snippet tagged `for-loop`
//     draws a ring; one tagged `window-function` draws a grid of cells. The
//     table below is the whole of it, and the order a snippet lists its topics
//     in is the order they are tried, so the mapping is stable for a run and
//     stable between runs.
//  2. Failing that, a hash of the snippet's id, modulo eight. The corpus has
//     498 distinct topics over 249 snippets and a table that named all of them
//     would be a second corpus to maintain; the hash covers the tail and is
//     just as deterministic.
//
// Nothing here reads the clock, the seed or the run, so the same snippet is
// the same picture in every run on every machine.

