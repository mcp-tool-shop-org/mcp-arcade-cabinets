export const TOPIC_KINDS: ReadonlyMap<string, PieceKind> = new Map<string, PieceKind>([
  ...Object.entries(TOPIC_TABLE),
  // Two topics the corpus really carries whose names are already members of
  // every object. They are entries here rather than lines in the literal
  // above because a property called `constructor` in an object type is the
  // one `Object.prototype` declares, and cannot be a piece kind as well.
  ['constructor', 'function'],
  ['toString', 'message'],
]);

/**
 * The tile a shipped snippet draws. Total: every snippet gets one of the
 * eight, and the same snippet always gets the same one.
 */
export function pieceKindOf(snippet: Pick<Snippet, 'id' | 'topics'>): PieceKind {
  for (const topic of snippet.topics) {
    const named = TOPIC_KINDS.get(topic);
    if (named) return named;
  }
  return PIECE_KINDS[hashString(snippet.id) % PIECE_KINDS.length]!;
}

/** True when the topics named the kind, rather than the id's hash. */
export function namedByTopic(snippet: Pick<Snippet, 'topics'>): boolean {
  return snippet.topics.some((topic) => TOPIC_KINDS.has(topic));
}
